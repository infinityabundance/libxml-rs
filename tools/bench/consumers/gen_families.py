#!/usr/bin/env python3
"""gen_families.py — deterministically render the §16.12/§16.13 per-family
structural-extraction stylesheets from `families.json`.

The stylesheets are fixed before any timing and are committed under `xslt/`.
Each counts the family's characteristic element names plus total elements and
total text length: plausible, document-appropriate structural extraction that
does real XSLT work without depending on any external stylesheet package.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
XSLT_DIR = os.path.join(HERE, "xslt")

TEMPLATE = """<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/bench/consumers/gen_families.py from families.json.
     Fixed before timing; do not edit by hand. -->
<xsl:stylesheet version="1.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform">
  <xsl:output method="xml" encoding="UTF-8" indent="no" omit-xml-declaration="yes"/>
  <xsl:template match="/">
    <summary>
      <total><xsl:value-of select="count(//*)"/></total>
{counts}      <textlen><xsl:value-of select="string-length(string(.))"/></textlen>
    </summary>
  </xsl:template>
</xsl:stylesheet>
"""


def main() -> None:
    os.makedirs(XSLT_DIR, exist_ok=True)
    with open(os.path.join(HERE, "families.json"), encoding="utf-8") as f:
        doc = json.load(f)
    for fam, spec in doc["families"].items():
        lines = []
        for name in spec["xslt_names"]:
            lines.append(
                "      <n name=\"%s\"><xsl:value-of "
                "select=\"count(//*[local-name()='%s'])\"/></n>\n" % (name, name))
        with open(os.path.join(XSLT_DIR, "%s.xsl" % fam), "w", encoding="utf-8") as f:
            f.write(TEMPLATE.format(counts="".join(lines)))
        print("wrote xslt/%s.xsl" % fam)


if __name__ == "__main__":
    main()
