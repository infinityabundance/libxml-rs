#!/usr/bin/env python3
"""ABI-FUNCTION-SIGNATURE court (11.1-Z.2; hardened 11.1-Z.3) — three-way C
function-prototype mirror.

For every externally relevant function the court proves the triangle:

    oracle Clang C prototype            (system headers, clang AST)
              ↕  (must match at SOURCE + MACHINE-ABI level)
    candidate installed C prototype     (include/, clang AST)
              ↕  (must match at MACHINE-ABI level)
    actual Rust extern "C" signature    (src/, extracted from source)

Two fingerprints are measured per symbol (11.1-Z.3):

    SOURCE_PROTOTYPE_FINGERPRINT
        canonical/desugared base type, pointer depth, const/restrict where
        source-visible, typedef identity where important, FULL function-pointer
        signature (not just "fnptr"), variadic, argument count, return type,
        calling convention — compared between oracle and candidate headers.

    MACHINE_ABI_FINGERPRINT
        ABI class (int/float/ptr/fnptr/void/struct), width, SIGNEDNESS
        (int vs uint vs long vs ulong vs size_t/usize ...), pointer depth,
        struct-by-value identity, callback ABI, variadic — compared between
        oracle/candidate headers AND candidate headers/Rust implementation
        (size_t ≡ usize, c_long ≡ long, ... at the machine level).

The x86-64 assembly variadic shims (xmlGenericError / xsltGenericError
default printers, xmlStrPrintf, xsltTransformError, the four legacy SAX v1
handlers, and the 13 xmlTextWriterWriteFormat* shims generated by the
vfmt_shim!/fmt_stub! macros, R-000161/R-000176) have C-variadic prototypes
but Rust signatures that are the documented shim form; they are CLASSIFIED
in ASM_SHIMS / GENERATED_MACRO_SHIMS, never silently skipped.

Fail-closed + oracle-isolated (11.1-Z.3):

  - the oracle plane compiles with ONLY system include paths
    (/usr/include/libxml2 + the default system paths) and the candidate plane
    with ONLY repo include paths — the two universes are fully separated;
  - every resolved include is recorded (`clang -H`) and cross-contamination
    (an oracle parse resolving a repo header, or a candidate parse resolving
    a system project header) is a finding;
  - a header clang cannot parse is a finding (never silently dropped);
  - a function declared by the candidate header without a measured Rust
    `extern "C" fn` is a finding unless it has a named disposition
    (DATA / ASM shim / macro-generated shim / candidate-header auxiliary);
  - every declaration is accounted: silent_omissions must be 0.

This is the function-level equivalent of the struct-mirror court (RUST-MIRROR-
ABI): a signature mismatch here means a C caller following the installed
header passes arguments/expects a return that the Rust implementation
misreads — the xmlGcMemSetup class of bug (11.1-Z.2, R-000176).

Usage:
  function_signature_court.py            # run the court, write a receipt
  function_signature_court.py --report   # print every finding in detail
"""
