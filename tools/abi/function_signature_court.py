def clang_version():
    r = subprocess.run(["clang", "--version"], capture_output=True, text=True)
    return r.stdout.splitlines()[0] if r.stdout else "unknown"


def clang_prototypes(header_dirs, include_paths, forbidden_roots, side):
    """Extract per-header FunctionDecls/TypedefDecls via clang AST dumps
    (text mode: every decl carries its true declaring file).

    Returns (decls, stats, contamination, typedefs) where typedefs is
    (enums:set, fnptrs:set, sigs:dict name->desugared qualType). All typedefs
    seen while parsing are collected (project + libc; the project uses the
    xml*/xslt*/exslt* prefixes so there is no collision), which lets the
    fingerprints canonically desugar `xmlChar`, `xmlNodePtr`, `size_t`, ...
    uniformly on both sides. FunctionDecls are kept ONLY when their declaring
    file is the parsed header itself (main-file decl-loc, or a decl-loc whose
    path resolves to the target header — the wrapper case for
    non-self-contained oracle headers, see ORACLE_HEADER_PREREQS). Resolved
    include origins are recorded via `clang -H` and checked against
    forbidden_roots (cross-universe contamination)."""
    decls = {}
    enums, fnptrs, sigs = set(), set(), {}
    stats = {"discovered": 0, "parsed": 0, "failed": []}
    contamination = []
    inc = ["-I"] + [p for path in include_paths for p in (path,)]
    for d in header_dirs:
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".h"):
                continue
            stats["discovered"] += 1
            path = os.path.join(d, fn)
            target_real = os.path.realpath(path)
            parse_path = path
            prereqs = ORACLE_HEADER_PREREQS.get(fn) if side == "oracle" else None
            if prereqs:
                wrapper = os.path.join(ROOT, "target", f"fsc-{side}-{fn}.c")
                os.makedirs(os.path.dirname(wrapper), exist_ok=True)
                with open(wrapper, "w") as w:
                    for p in prereqs:
                        w.write(f"#include {p}\n")
                    w.write(f'#include "{path}"\n')
                parse_path = wrapper
            r = subprocess.run(
                ["clang", "-Xclang", "-ast-dump", "-fsyntax-only", "-H"] + inc + [parse_path],
                capture_output=True, text=True)
            if r.returncode != 0:
                stats["failed"].append({"header": os.path.relpath(path, ROOT),
                                        "stderr": r.stderr[-1500:]})
                continue
            stats["parsed"] += 1
            header_text = open(path, encoding="utf-8", errors="replace").read()
            # -H include resolution log (stderr): ".... /abs/path.h"
            for line in r.stderr.splitlines():
                m = re.match(r"^\s*\.+\s+(/\S+)\s*$", line)
                if m:
                    rp = os.path.realpath(m.group(1))
                    for root in forbidden_roots:
                        if rp.startswith(root + os.sep) or rp == root:
                            contamination.append({"side": side, "header": fn,
                                                  "resolved": rp, "root": root})
            for line in r.stdout.splitlines():
                m = FD_RE.match(line)
                if m and "implicit" not in line:
                    loc_tok, name, typ = m.group(1), m.group(2), m.group(3)
                    if re.match(r"^(line|col):", loc_tok):
                        is_target = True  # declared in the parsed header itself
                    else:
                        p = loc_tok.rsplit(":", 2)[0]
                        is_target = os.path.realpath(p) == target_real
                    if not is_target:
                        continue
                    # final gate: the function name must be textually written
                    # in the target header (clang's location printing can
                    # degenerate for libc redeclarations to the main-file
                    # form; a declaration the header does not contain cannot
                    # belong to it)
                    if not re.search(r"\b" + re.escape(name) + r"\s*\x28", header_text):
                        continue
                    q = typ
                    ret = q.split("(", 1)[0].strip() if "(" in q else q
                    inner = q.split("(", 1)[1].rsplit(")", 1)[0] if "(" in q else ""
                    params = [p.strip() for p in split_params(inner)]
                    # C `(void)` is zero parameters (clang renders it as one
                    # "void" param); Rust declares `fn f()`. Normalize.
                    if params == ["void"]:
                        params = []
                    variadic = bool(re.search(r"\.\.\.", inner))
                    if name not in decls:
                        decls[name] = {"ret": ret, "params": params,
                                       "variadic": variadic, "header": fn}
                    continue
                m = TD_RE.match(line)
                if m and "implicit" not in line:
                    name, qt = m.group(1), m.group(2)
                    sigs[name] = qt
                    if qt.startswith("enum ") or " enum " in qt:
                        enums.add(name)
                    elif is_fnptr_text(qt) or "Func" in qt:
                        fnptrs.add(name)
    return decls, stats, contamination, (enums, fnptrs, sigs)


FD_RE = re.compile(
    r"^[|` ]*-FunctionDecl\s+0x[0-9a-f]+(?:\s+prev\s+0x[0-9a-f]+)?\s+"
    r"<[^>]*>\s+(\S+)\s+([A-Za-z_]\w*)\s+'(.+)'")
TD_RE = re.compile(
    r"^[|` ]*-TypedefDecl\s+0x[0-9a-f]+(?:\s+prev\s+0x[0-9a-f]+)?\s+"
    r"<[^>]*>\s+\S+\s+(?:(?:referenced|implicit)\s+)?([A-Za-z_]\w*)\s+'(.+)'")


def rust_fn_signatures():
    """Extract {name: {ret, params:[raw], variadic, path}} for every
    `extern "C" fn` in src/ (multi-line aware; const/unsafe modifiers
    allowed). Doc-comment copies are excluded by requiring the declaration
    to start a line."""
    out = {}
    pat = re.compile(
        r'(?m)^\s*(?:pub(?:\s*\([^)]*\))?\s+)?(?:(?:unsafe|const)\s+)*'
        r'extern\s+"C"\s+fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(')
    for dirpath, _dirs, files in os.walk(SRC):
        for fn in files:
            if not fn.endswith(".rs"):
                continue
            path = os.path.join(dirpath, fn)
            text = open(path, encoding="utf-8", errors="replace").read()
            for m in pat.finditer(text):
                name = m.group(1)
                i = m.end()
                depth = 1  # the matched '(' is open
                while i < len(text) and depth > 0:
                    ch = text[i]
                    if ch == "(":
                        depth += 1
                    elif ch == ")":
                        depth -= 1
                    i += 1
                params_text = text[m.end():i - 1]
                head = text[i:].split("{", 1)[0]
                variadic = bool(re.search(r'(?<!\.)\.\.\.', params_text))
                params = [rust_param_type(p) for p in split_params(params_text)]
                ret = "()"
                rm = re.search(r'->\s*([^{;]+)', head)
                if rm:
                    ret = rm.group(1).strip().rstrip()
                out[name] = {"ret": ret, "params": params,
                             "variadic": variadic,
                             "path": os.path.relpath(path, ROOT)}
    return out


def rust_param_type(p):
    """Strip the parameter name: `ctxt: *mut _xmlNode` -> `*mut _xmlNode`."""
    depth = 0
    prev = ""
    for i, ch in enumerate(p):
        if ch in "<([":
            depth += 1
        elif ch in ">)]" and not (ch == ">" and prev == "-"):
            depth -= 1
        elif ch == ":" and depth == 0:
            return p[i + 1:].strip()
        prev = ch
    return p.strip()


def macro_generated_exports():
    """Names of `extern "C" fn`s generated by export macros (not visible to
    the textual extractor): the xmlTextWriterWriteFormat* x86-64 variadic
    asm shims (vfmt_shim!) and their non-x86-64 stubs (fmt_stub!)."""
    names = set()
    text = open(os.path.join(SRC, "xml", "writer", "mod.rs"), encoding="utf-8").read()
    for m in re.finditer(r'(?m)^\s*(vfmt_shim|fmt_stub)!\s*\((.*?)\)\s*;', text, re.S):
        macro, body = m.group(1), m.group(2)
        args = split_params(body)
        if macro == "vfmt_shim":
            if args:
                names.add(args[0].strip())
        else:
            for a in args:
                names.add(a.strip())
    return names


# ── the court ──────────────────────────────────────────────────────────────

def run_court(report=False):
    findings = []
    classified = []
    compared = 0
    ok = 0

    oracle_decls, oracle_stats, oracle_contam, oracle_typedefs = clang_prototypes(
        ORACLE_HEADER_DIRS, ORACLE_INCLUDE_PATHS, ORACLE_FORBIDDEN_ROOTS, "oracle")
    cand_decls, cand_stats, cand_contam, cand_typedefs = clang_prototypes(
        CAND_HEADER_DIRS, CAND_INCLUDE_PATHS, CAND_FORBIDDEN_ROOTS, "candidate")
    cand_enums, cand_fnptrs, cand_sigs = cand_typedefs
    oracle_enums, oracle_fnptrs, oracle_sigs = oracle_typedefs

    # header parse failures are findings (fail-closed, 11.1-Z.3)
    for f in oracle_stats["failed"] + cand_stats["failed"]:
        findings.append({"symbol": "-", "plane": "header-parse",
                         "kind": "header-parse-failure",
                         "header": f["header"], "detail": f["stderr"][-1200:]})
    for c in oracle_contam + cand_contam:
        findings.append({"symbol": "-", "plane": "include-origin",
                         "kind": "include-contamination",
                         "detail": f"{c['side']} header {c['header']} resolved "
                                   f"{c['resolved']} inside forbidden root {c['root']}"})

    rust = rust_fn_signatures()
    macro_shims = macro_generated_exports()

    # ── Plane 1 vs 2: oracle headers ↔ candidate headers ─────────────────────
    for name, oc in sorted(oracle_decls.items()):
        if name in ORACLE_INTERNAL_GLOBALS:
            classified.append({"symbol": name, "plane": "oracle-vs-candidate",
                               "kind": "oracle-internal-indirection",
                               "detail": "globals.h DLL-import backing name; candidate exports the public name"})
            continue
        if name in HEADER_DECLARED_ORACLE_DSO_ABSENT:
            classified.append({"symbol": name, "plane": "oracle-vs-candidate",
                               "kind": "header-declared-oracle-dso-absent",
                               "detail": HEADER_DECLARED_ORACLE_DSO_ABSENT[name]})
            continue
        cc = cand_decls.get(name)
        if cc is None:
            findings.append({"symbol": name, "plane": "oracle-vs-candidate",
                             "kind": "missing-in-candidate-header",
                             "detail": f"oracle: {oc['ret']}({', '.join(oc['params'])}) "
                                       f"[header {oc['header']}]"})
            continue
        compared += 1
        problems = []
        # SOURCE + MACHINE fingerprints for the return type
        o_ret_src, c_ret_src = c_source_fp(oc["ret"], oracle_enums, oracle_fnptrs, oracle_sigs), \
            c_source_fp(cc["ret"], cand_enums, cand_fnptrs, cand_sigs)
        o_ret_abi, c_ret_abi = c_abi_fp(oc["ret"], oracle_enums, oracle_fnptrs, oracle_sigs), \
            c_abi_fp(cc["ret"], cand_enums, cand_fnptrs, cand_sigs)
        if o_ret_src != c_ret_src:
            problems.append(f"return SOURCE {oc['ret']}({o_ret_src}) vs {cc['ret']}({c_ret_src})")
        if not abi_eq(o_ret_abi, c_ret_abi):
            problems.append(f"return ABI {oc['ret']}({o_ret_abi}) vs {cc['ret']}({c_ret_abi})")
        if len(oc["params"]) != len(cc["params"]):
            problems.append(f"arg count oracle {len(oc['params'])} vs candidate {len(cc['params'])}")
        else:
            for i, (op, cp) in enumerate(zip(oc["params"], cc["params"])):
                o_src = c_source_fp(op, oracle_enums, oracle_fnptrs, oracle_sigs)
                c_src = c_source_fp(cp, cand_enums, cand_fnptrs, cand_sigs)
                o_abi = c_abi_fp(op, oracle_enums, oracle_fnptrs, oracle_sigs)
                c_abi = c_abi_fp(cp, cand_enums, cand_fnptrs, cand_sigs)
                if o_src != c_src:
                    problems.append(f"arg{i} SOURCE {op}({o_src}) vs {cp}({c_src})")
                if not abi_eq(o_abi, c_abi):
                    problems.append(f"arg{i} ABI {op}({o_abi}) vs {cp}({c_abi})")
        if oc["variadic"] != cc["variadic"]:
            problems.append(f"variadic oracle {oc['variadic']} vs candidate {cc['variadic']}")
        if problems:
            findings.append({"symbol": name, "plane": "oracle-vs-candidate",
                             "kind": "prototype-drift",
                             "detail": "; ".join(problems)})
        else:
            ok += 1

    # ── Plane 2 vs 3: candidate headers ↔ Rust extern signatures ─────────────
    unmeasured = []
    for name, cc in sorted(cand_decls.items()):
        if name in DATA_EXPORTS:
            classified.append({"symbol": name, "plane": "candidate-vs-rust",
                               "kind": "data-export", "detail": "DATA function-pointer/global symbol"})
            continue
        if name in ASM_SHIMS:
            classified.append({"symbol": name, "plane": "candidate-vs-rust",
                               "kind": "asm-shim",
                               "detail": "x86-64 variadic asm shim (R-000161); declared C arity is a Rust-side shim form"})
            continue
        if name in macro_shims:
            classified.append({"symbol": name, "plane": "candidate-vs-rust",
                               "kind": "generated-macro-shim",
                               "detail": "variadic asm shim generated by vfmt_shim!/fmt_stub! "
                                         "(writer/mod.rs); the fixed-arg ABI is captured from registers and "
                                         "forwarded to the measured xmlTextWriterWriteVFormat* counterpart"})
            continue
        if name.startswith(CANDIDATE_HEADER_AUXILIARY):
            classified.append({"symbol": name, "plane": "candidate-vs-rust",
                               "kind": "candidate-header-auxiliary",
                               "detail": "declared in the vendored candidate-only trio.h (the oracle 1.1.45 "
                                         "ships no trio.h); not part of the drop-in parity surface"})
            continue
        rs = rust.get(name)
        if rs is None:
            unmeasured.append(name)
            findings.append({"symbol": name, "plane": "candidate-vs-rust",
                             "kind": "candidate-decl-not-measured",
                             "detail": f"candidate header {cc['header']} declares "
                                       f"{cc['ret']}({', '.join(cc['params'])}) but no Rust extern \"C\" fn "
                                       f"is measured for it"})
            continue
        compared += 1
        problems = []
        cret = c_abi_fp(cc["ret"], cand_enums, cand_fnptrs, cand_sigs)
        rret = rust_abi_fp(rs["ret"], cand_enums, cand_fnptrs)
        if not abi_eq(cret, rret):
            problems.append(f"return ABI {cc['ret']}({cret}) vs Rust {rs['ret']}({rret})")
        if len(cc["params"]) != len(rs["params"]):
            problems.append(
                f"arg count {len(cc['params'])} ({', '.join(cc['params'])}) "
                f"vs Rust {len(rs['params'])} ({', '.join(rs['params'])})")
        else:
            for i, (cp, rp) in enumerate(zip(cc["params"], rs["params"])):
                cnorm = c_abi_fp(cp, cand_enums, cand_fnptrs, cand_sigs)
                rnorm = rust_abi_fp(rp, cand_enums, cand_fnptrs)
                if not abi_eq(cnorm, rnorm):
                    problems.append(f"arg {i} {cp}({cnorm}) vs Rust {rp}({rnorm})")
        if cc["variadic"] != rs["variadic"]:
            problems.append(f"variadic {cc['variadic']} vs Rust {rs['variadic']}")
        if problems:
            findings.append({"symbol": name, "plane": "candidate-vs-rust",
                             "kind": "signature-mismatch",
                             "detail": "; ".join(problems),
                             "rust_path": rs["path"]})
        else:
            ok += 1

    # unclassified Rust types seen in the measured set (named disposition)
    unclassified_rust = sorted({
        (rp, rs["path"]) for rs in rust.values() for rp in rs["params"]
        if rust_abi_fp(rp, cand_enums, cand_fnptrs) == ("other", 0, None, 0)
    } | {(rs["ret"], rs["path"]) for rs in rust.values()
          if rust_abi_fp(rs["ret"], cand_enums, cand_fnptrs) == ("other", 0, None, 0)})

    oracle_absent = sorted(HEADER_DECLARED_ORACLE_DSO_ABSENT)
    silent_omissions = (len(oracle_stats["failed"]) + len(cand_stats["failed"])
                        + len(unmeasured) + len(unclassified_rust))
    verdict = "FAIL" if (findings or silent_omissions > 0) else "PASS"

    ts = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    receipt = {
        "court": "ABI-FUNCTION-SIGNATURE",
        "case": "ABI-FUNCTION-SIGNATURE-001",
        "phase": "11.1-Z.3",
        "timestamp": ts,
        "schema": "function-signature-court-2",
        "toolchain": {"clang": clang_version()},
        "planes": {
            "oracle": "system headers via clang AST (isolated include env)",
            "candidate_headers": "include/ via clang AST (isolated include env)",
            "rust": "src/ extern \"C\" fn extraction (const/unsafe aware)",
        },
        "environments": {
            "oracle_include_paths": ORACLE_INCLUDE_PATHS,
            "candidate_include_paths": CAND_INCLUDE_PATHS,
            "oracle_forbidden_roots": [os.path.relpath(r, ROOT) for r in ORACLE_FORBIDDEN_ROOTS],
            "candidate_forbidden_roots": [os.path.relpath(r, ROOT) for r in CAND_FORBIDDEN_ROOTS],
        },
        "fingerprints": {
            "source": "SOURCE_PROTOTYPE_FINGERPRINT (canonical base type, pointer depth, "
                      "pointee const/restrict, typedef identity, full fn-pointer signature, "
                      "variadic, arg count, return type, calling convention)",
            "machine": "MACHINE_ABI_FINGERPRINT (ABI class, width, signedness, pointer depth, "
                       "struct-by-value identity, callback ABI, variadic)",
        },
        "accounting": {
            "oracle_headers_discovered": oracle_stats["discovered"],
            "oracle_headers_parsed": oracle_stats["parsed"],
            "oracle_headers_failed": len(oracle_stats["failed"]),
            "candidate_headers_discovered": cand_stats["discovered"],
            "candidate_headers_parsed": cand_stats["parsed"],
            "candidate_headers_failed": len(cand_stats["failed"]),
            "oracle_fn_decls": len(oracle_decls),
            "candidate_fn_decls": len(cand_decls),
            "rust_signatures_measured": len(rust),
            "asm_shims_classified": len(ASM_SHIMS),
            "data_exports_classified": len(DATA_EXPORTS),
            "generated_macro_exports_classified": len(macro_shims),
            "candidate_header_auxiliary_classified": len([1 for n in cand_decls
                                                          if n.startswith(CANDIDATE_HEADER_AUXILIARY)]),
            "oracle_internal_globals_classified": len(ORACLE_INTERNAL_GLOBALS),
            "header_declared_oracle_dso_absent": len(oracle_absent),
            "unmeasured_functions": len(unmeasured),
            "unclassified_rust_types": len(unclassified_rust),
            "silent_omissions": silent_omissions,
        },
        "summary": {"compared": compared, "ok": ok, "findings": len(findings)},
        "classified": classified,
        "findings": findings,
        "verdict": verdict,
    }
    os.makedirs(RECEIPTS, exist_ok=True)
    rp = os.path.join(RECEIPTS, f"abi-function-signature-{ts}.json")
    with open(rp, "w") as f:
        json.dump(receipt, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print(f"receipt -> {rp}")
    a = receipt["accounting"]
    print(f"oracle headers {a['oracle_headers_parsed']}/{a['oracle_headers_discovered']} parsed, "
          f"{a['oracle_headers_failed']} failed; candidate {a['candidate_headers_parsed']}/"
          f"{a['candidate_headers_discovered']} parsed, {a['candidate_headers_failed']} failed")
    print(f"fn decls oracle={a['oracle_fn_decls']} candidate={a['candidate_fn_decls']} "
          f"rust measured={a['rust_signatures_measured']}")
    print(f"compared={compared} ok={ok} findings={len(findings)} "
          f"silent_omissions={silent_omissions} verdict={verdict}")
    if report:
        for f_ in findings:
            print(f"  [{f_['kind']}] {f_['symbol']}: {f_['detail']}")
    return 0 if verdict == "PASS" else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    args = ap.parse_args()
    return run_court(report=args.report)


if __name__ == "__main__":
    sys.exit(main())
